const dictionaries: Record<Language, Record<TranslationKey, string>> = {
  en: english,
  hi: hindi,
  mr: marathi,
};

export function isLanguage(value: unknown): value is Language {
  return languageOptions.some((option) => option.code === value);
}

export function parseLanguage(value: unknown): Language {
  return isLanguage(value) ? value : 'en';
}

export function translate(
  language: Language,
  key: string,
  values: Record<string, string | number> = {},
): string {
  const template = dictionaries[language]?.[key as TranslationKey]
    ?? english[key as TranslationKey]
    ?? english['common.unavailable'];
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_, name: string) =>
    String(values[name] ?? ''),
  );
}

export function getLanguagePreference(storage: Pick<Storage, 'getItem'>): Language {
  try {
    return parseLanguage(storage.getItem(languageStorageKey));
  } catch {
    return 'en';
  }
}

export const requiredParentTranslationKeys = Object.keys(english) as TranslationKey[];

export function getLocale(language: Language): string {
  return languageOptions.find((option) => option.code === language)?.locale ?? 'en-GB';
}
